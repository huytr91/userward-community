export type TranslationKey = keyof typeof en;
export type TranslateVars = Record<string, string | number>;
export type Translator = (key: TranslationKey, vars?: TranslateVars) => string;
export const translationKeys = Object.keys(en) as TranslationKey[];

export function translate(locale: AppLocale, key: TranslationKey, vars?: TranslateVars) {
  let text = dictionaries[locale]?.[key] ?? en[key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

export function detectLocale(languages: readonly string[] = []): AppLocale {
  for (const language of languages) {
    const base = language.toLowerCase().split("-")[0];
    if (supportedLocales.includes(base as AppLocale)) return base as AppLocale;
  }
  return "en";
}
